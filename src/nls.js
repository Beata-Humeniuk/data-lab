const TRANSLATIONS = { pl: PL };

function baseLanguage(tag) {
  return String(tag || 'en').toLowerCase().split(/[-_]/)[0];
}

const PLURAL_RULES = {
  en: (n) => (n === 1 ? 0 : 1),
  pl: (n) => {
    if (n === 1) return 0;
    const d = n % 10;
    const h = n % 100;
    return d >= 2 && d <= 4 && (h < 12 || h > 14) ? 1 : 2;
  },
};

function forLanguage(tag) {
  const lang = baseLanguage(tag);
  const table = TRANSLATIONS[lang] || {};
  const rule = PLURAL_RULES[lang] || PLURAL_RULES.en;

  const lookup = (key) => {
    const value = table[key];
    if (typeof value === 'string' && value !== '') return value;
    if (Array.isArray(value) && value.length) return value;
    return EN[key];
  };

  const t = (key, params) => {
    const text = lookup(key);
    if (typeof text !== 'string') return key;
    return text.replace(/\{(\w+)\}/g, (whole, name) =>
      params && name in params ? String(params[name]) : whole);
  };

  const plural = (key, n) => {
    const forms = lookup(key);
    if (!Array.isArray(forms) || !forms.length) return typeof forms === 'string' ? forms : key;
    return forms[Math.min(rule(n), forms.length - 1)];
  };

  // Flat tables for injecting into the webview: every key resolved with the
  // English fallback already applied, split into strings and plural forms.
  const stringsTable = () => {
    const out = {};
    for (const key of Object.keys(EN)) {
      const value = lookup(key);
      if (typeof value === 'string') out[key] = value;
    }
    return out;
  };
  const formsTable = () => {
    const out = {};
    for (const key of Object.keys(EN)) {
      const value = lookup(key);
      if (Array.isArray(value)) out[key] = value;
    }
    return out;
  };

  return { lang: PLURAL_RULES[lang] ? lang : 'en', t, plural, stringsTable, formsTable };
}

module.exports = { forLanguage, baseLanguage, EN, TRANSLATIONS };
